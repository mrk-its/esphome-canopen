#pragma once

// PR 8 hardware test: OD handlers (canopen::OdObject) on our own node, accessed with the local SDO client and
// write_od(). register_objects() runs from on_boot, before the hub's setup().

#include "esphome/components/canopen/canopen.h"
#include "esphome/core/log.h"

namespace od_handler_test {

using namespace esphome::canopen;
static const char *const TAG = "od_handler_test";

// 0x5000: u32 RW, writes counted
struct Counted : OdObject {
  uint32_t value{0};
  int writes{0};
  OdResult od_write(OdStream stream, const void *buf, size_t count, size_t *done) {
    this->writes++;
    return stream.write_original(buf, count, done);
  }
};

// 0x5001: read-only domain without storage, 100 bytes 0..99 generated in chunks
struct Generated : OdObject {
  OdResult od_read(OdStream stream, void *buf, size_t count, size_t *done) {
    if (stream.offset() == 0)
      stream.set_size(100);
    size_t n = std::min(count, stream.size() - stream.offset());
    for (size_t i = 0; i < n; i++)
      static_cast<uint8_t *>(buf)[i] = stream.offset() + i;
    stream.set_offset(stream.offset() + n);
    *done = n;
    return stream.offset() < stream.size() ? OdResult::OD_RESULT_PARTIAL : OdResult::OD_RESULT_OK;
  }
};

static Counted counted;
static Generated generated;
static CANopenComponent *hub = nullptr;

inline void register_objects(CANopenComponent *co) {
  hub = co;
  auto &od = co->get_od();
  od.add_var(0x5000, OD_READ_WRITE, &counted.value, sizeof(counted.value));
  od.set_object(0x5000, &counted);
  od.add_var(0x5001, OD_READ, nullptr, 0);
  od.set_object(0x5001, &generated);
}

inline void check(bool ok, const char *what) { ESP_LOGI(TAG, "%s %s", ok ? "PASS" : "FAIL", what); }

inline void run(uint8_t own_id) {
  // local SDO write: goes through the handler
  hub->write_sdo<uint32_t>(own_id, 0x5000, 0, 0xCAFE, +[](void *, const SDOReply &r) {
    check(r.ok() && counted.value == 0xCAFE && counted.writes == 1, "SDO write 0x5000 through od_write()");
    // write_od(): synchronous, same handler
    uint32_t v = 0xBEEF;
    OdResult res = hub->write_od(0x5000, 0, &v, sizeof(v));
    check(res == OdResult::OD_RESULT_OK && counted.value == 0xBEEF && counted.writes == 2, "write_od 0x5000");
    uint8_t b = 1;
    check(hub->write_od(0x5001, 0, &b, 1) == OdResult::OD_RESULT_READ_ONLY, "write_od of a read-only entry -> READ_ONLY");
    // read back through the default od_read()
    hub->read_sdo<uint32_t>(0x7F, 0x5000, 0, +[](void *, const SDOReply &r) {
      check(r.ok() && r.value == 0xBEEF, "SDO read 0x5000 (default od_read)");
    }, nullptr);
    // partial reads of the generated domain
    hub->read_sdo_data(0x7F, 0x5001, 0, +[](void *, const SDOReply &r) {
      bool ok = r.ok() && r.len == 100;
      for (size_t i = 0; ok && i < r.len; i++)
        ok = r.data[i] == i;
      ESP_LOGI(TAG, "0x5001: %s, %u bytes", LOG_STR_ARG(sdo_result_to_string(r.result)), (unsigned) r.len);
      check(ok, "SDO read 0x5001: 100 generated bytes (PARTIAL reads)");
    }, nullptr);
  }, nullptr);
}

}  // namespace od_handler_test
