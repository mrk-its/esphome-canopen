#!/usr/bin/env python3
"""Copy the `canopen` hub from the ESPHome fork into components/canopen (a generated copy: never edit it here).

The hub is developed (and tested) in mrk-its/esphome, branch canopen-full, from where it goes upstream PR by PR.
This repo ships a copy so users need one external_components source. The copy is taken from a commit, not from the
working tree, and components/canopen/SYNCED_FROM records that commit and a digest of the files; test/test_hub_copy.py
fails if the copy differs from it.

Usage: scripts/sync_hub.py [--repo ~/repos/esphome] [--ref canopen-full] [--worktree]

--worktree copies the fork's working tree instead (uncommitted hub changes, e.g. for a hardware test); the copy is
then marked as such, and test_hub_copy.py fails until the hub is committed and synced from a commit.
"""

import argparse
import hashlib
import io
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "components" / "canopen"
SOURCE_PATH = "esphome/components/canopen"
MARKER = "SYNCED_FROM"
UPSTREAM_URL = "https://github.com/mrk-its/esphome"


def tree_digest(path: Path) -> str:
    """sha256 over the relative paths and contents of the files under path (MARKER and caches excluded)."""
    digest = hashlib.sha256()
    for file in sorted(p for p in path.rglob("*") if p.is_file()):
        rel = file.relative_to(path).as_posix()
        if rel == MARKER or "__pycache__" in file.parts:
            continue
        digest.update(rel.encode() + b"\0" + file.read_bytes() + b"\0")
    return digest.hexdigest()


def read_marker(path: Path = DEST) -> dict[str, str]:
    """The `key: value` lines of SYNCED_FROM."""
    lines = (path / MARKER).read_text(encoding="utf-8").splitlines()
    return dict(
        line.split(": ", 1)
        for line in lines
        if ": " in line and not line.startswith("#")
    )


def extract(repo: Path, commit: str, dest: Path) -> None:
    """The hub's files at commit into dest (empty or missing)."""
    archive = subprocess.run(
        ["git", "-C", str(repo), "archive", "--format=tar", commit, SOURCE_PATH],
        check=True,
        capture_output=True,
    ).stdout
    prefix = SOURCE_PATH + "/"
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        for member in tar.getmembers():
            if not member.isfile() or not member.name.startswith(prefix):
                continue
            target = dest / member.name[len(prefix) :]
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(tar.extractfile(member).read())
            target.chmod(member.mode & 0o777)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument(
        "--repo",
        type=Path,
        default=Path.home() / "repos" / "esphome",
        help="ESPHome fork checkout",
    )
    parser.add_argument(
        "--ref", default="canopen-full", help="branch, tag or commit to copy"
    )
    parser.add_argument(
        "--worktree",
        action="store_true",
        help="copy the working tree (development only)",
    )
    args = parser.parse_args()
    if args.worktree:
        args.ref = "HEAD"

    commit = subprocess.run(
        [
            "git",
            "-C",
            str(args.repo),
            "rev-parse",
            "--verify",
            f"{args.ref}^{{commit}}",
        ],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    subject = subprocess.run(
        ["git", "-C", str(args.repo), "log", "-1", "--format=%s", commit],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()

    if DEST.exists():
        shutil.rmtree(DEST)
    DEST.mkdir(parents=True)
    if args.worktree:
        shutil.copytree(
            args.repo / SOURCE_PATH,
            DEST,
            dirs_exist_ok=True,
            ignore=shutil.ignore_patterns("__pycache__"),
        )
    else:
        extract(args.repo, commit, DEST)
    (DEST / MARKER).write_text(
        "# Generated by scripts/sync_hub.py: this directory is a copy, don't edit it here.\n"
        f"repo: {UPSTREAM_URL}\n"
        f"ref: {args.ref}\n"
        f"commit: {commit}\n"
        f"subject: {subject}\n"
        + (
            "worktree: yes (uncommitted changes, development only)\n"
            if args.worktree
            else ""
        )
        + f"digest: {tree_digest(DEST)}\n",
        encoding="utf-8",
    )
    source = "working tree" if args.worktree else args.ref
    print(f"components/canopen <- {source} {commit[:10]} ({subject})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
